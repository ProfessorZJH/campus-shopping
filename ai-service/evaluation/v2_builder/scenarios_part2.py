from __future__ import annotations


def _msg(role: str, content: str) -> dict[str, str]:
    return {"role": role, "content": content}


def _bp(
    *,
    query_type: str,
    family_id: str,
    split: str,
    original_query: str,
    rationale: str,
    action: str = "RECOMMEND",
    smoke: bool = False,
    tags: list[str] | None = None,
    task_scopes: list[str] | None = None,
    conversation_context: list[dict[str, str]] | None = None,
    actor_ref: str = "buyer",
    budget_cent: int | None = None,
    quantity: int | float | None = 1,
    req_attrs: dict[str, str] | None = None,
    forb_attrs: dict[str, str] | None = None,
    budget_state: str | None = None,
    quantity_state: str | None = None,
    clarification_terms: list[str] | None = None,
    forbidden_facts: list[str] | None = None,
    no_match_terms: list[str] | None = None,
    state_transition: dict | None = None,
    sensitive: bool = False,
    disputed: bool = False,
    targets: list[str] | None = None,
    secondary: list[str] | None = None,
    combos: list[str] | None = None,
    preferred_merchants: list[str] | None = None,
    prefer_cheapest: bool = False,
    force_no_match: bool = False,
    primary_ev: list[tuple[str, int]] | None = None,
    secondary_ev: list[tuple[str, int]] | None = None,
) -> dict:
    ctx = list(conversation_context or [])
    if action == "KNOWLEDGE_ONLY" and quantity == 1 and targets is None:
        eff_qty: int | float | None = None
    else:
        eff_qty = quantity

    b_state = budget_state or ("VALID" if budget_cent is not None else "UNSPECIFIED")
    if quantity_state is not None:
        q_state = quantity_state
    elif action == "CLARIFY" and (eff_qty is None or not (isinstance(eff_qty, int) and 1 <= eff_qty <= 99)):
        q_state = "INVALID"
    else:
        q_state = "VALID"

    expected: dict = {
        "action": action,
        "clarificationTerms": list(clarification_terms or []),
        "forbiddenFacts": list(forbidden_facts or []),
    }
    if no_match_terms is not None:
        expected["noMatchTerms"] = list(no_match_terms)

    tag_list = [query_type]
    for t in tags or []:
        if t not in tag_list:
            tag_list.append(t)

    return {
        "queryType": query_type,
        "familyId": family_id,
        "split": split,
        "smoke": bool(smoke),
        "tags": tag_list,
        "taskScopes": list(task_scopes or ["product", "recommendation"]),
        "originalQuery": original_query,
        "conversationContext": ctx,
        "actorRef": actor_ref,
        "intentGold": {
            "intent": action,
            "budgetState": b_state,
            "quantityState": q_state,
            "isFollowup": bool(ctx),
        },
        "constraints": {
            "budgetCent": budget_cent,
            "quantity": eff_qty,
            "requiredAttributes": dict(req_attrs or {}),
            "forbiddenAttributes": dict(forb_attrs or {}),
        },
        "expectedBehavior": expected,
        "stateTransition": state_transition,
        "sensitive": bool(sensitive),
        "disputed": bool(disputed),
        "rationale": rationale,
        "goldSpec": {
            "targetArchetypes": list(targets or []),
            "secondaryArchetypes": list(secondary or []),
            "comboArchetypes": list(combos or []),
            "preferredMerchantIds": list(preferred_merchants) if preferred_merchants is not None else None,
            "preferCheapest": bool(prefer_cheapest),
            "forceNoMatch": bool(force_no_match),
            "primaryEvidence": list(primary_ev or []),
            "secondaryEvidence": list(secondary_ev or []),
        },
    }


