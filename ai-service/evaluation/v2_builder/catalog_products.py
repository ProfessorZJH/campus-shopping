def _all_attr_combos(arch_key: str) -> list[dict[str, str]]:
    attrs = ARCHETYPES[arch_key]["attrs"]
    keys = list(attrs.keys())
    value_lists = [attrs[k] for k in keys]
    return [dict(zip(keys, prod)) for prod in itertools.product(*value_lists)]


def _compute_price_cent(
    arch_key: str,
    attrs: dict[str, str],
    *,
    merchant_id: str,
    slot_idx: int,
    is_same_name: bool,
) -> int:
    lex = ARCHETYPE_LEXICON[arch_key]
    price = int(lex["base"])
    deltas = lex["deltas"]
    for k, v in attrs.items():
        price += int(deltas[k][v])

    # 商户与商品槽位微调，制造真实跨店比价梯度（单位：10分=0.1元）
    merchant_adjust = {
        "m0": 0, "m1": -20, "m2": 30, "m3": 40, "m4": -30,
        "m5": 20, "m6": -40, "m7": 50, "m8": 60, "m9": 0,
    }[merchant_id]

    if is_same_name and merchant_id != "m9":
        # 同名跨店组拉开清晰且合理的门店价差（约 4%~12%），供 cross-merchant-compare 精确评测
        ring = (-8, 0, 9, -4, 6)[slot_idx % 5]
        pct = 1.0 + ring * 0.01
        raw = int(round((price * pct + merchant_adjust) / 10.0)) * 10
    elif merchant_id == "m9":
        # 停业商户 m9 七折超低价诱饵（约低 30%）
        raw = int(round((price * 0.70) / 10.0)) * 10
    else:
        slot_delta = ((slot_idx * 37 + len(arch_key)) % 9 - 4) * 20
        raw = int(round((price + merchant_adjust + slot_delta) / 10.0)) * 10

    return max(120, raw)


def build_products() -> tuple[list[dict[str, Any]], dict[str, dict[str, Any]]]:
    """确定性构建 480 款校园商品与精确 1,020 个多维规格 SKU。"""
    if sum(ARCHETYPE_COUNTS.values()) != 480 or set(ARCHETYPE_COUNTS) != set(ARCHETYPES):
        raise AssertionError("ARCHETYPE_COUNTS 必须覆盖全部 60 个原型且总和严格为 480")
    if sum(M9_TRAP_QUOTAS.values()) != 18:
        raise AssertionError("m9 诱饵商品数必须严格为 18")
    if len(UNPUBLISHED_ARCHETYPES) != 32 or len(DRAFT_ARCHETYPES) != 20:
        raise AssertionError("UNPUBLISHED(32) 或 DRAFT(20) 配额不匹配")

    # 第一步：生成 480 个商品骨架（确定性分配商户、发布状态、同名比价组、品牌、标题与差异化描述）
    product_plans: list[dict[str, Any]] = []
    brand_cursor = 0

    for arch_idx, (arch_key, arch_info) in enumerate(ARCHETYPES.items()):
        total_n = ARCHETYPE_COUNTS[arch_key]
        category = arch_info["category"]
        lex = ARCHETYPE_LEXICON[arch_key]
        active_merchants = [m for m in arch_info["merchants"] if m != "m9"]
        m9_quota = M9_TRAP_QUOTAS.get(arch_key, 0)
        has_unpub = 1 if arch_key in UNPUBLISHED_ARCHETYPES else 0
        has_draft = 1 if arch_key in DRAFT_ARCHETYPES else 0
        active_pub_n = total_n - m9_quota - has_unpub - has_draft
        if active_pub_n < 5:
            raise AssertionError(f"原型 {arch_key} 的活跃已上架商品数不足 5（当前 {active_pub_n}）")

        has_same_name_group = arch_key in SAME_NAME_GROUP_ARCHETYPES and len(active_merchants) >= 2
        same_group_id = f"sng-{arch_key}" if has_same_name_group else None
        same_active_slots = min(len(active_merchants), 3 if active_pub_n >= 6 and len(active_merchants) >= 3 else 2) if has_same_name_group else 0

        cat_brands = CATEGORY_BRAND_POOL[category]
        shared_brand = cat_brands[arch_idx % len(cat_brands)]
        shared_noun = lex["nouns"][0]
        shared_title = f"{shared_brand}{shared_noun}"

        # 构建槽位状态序列：先放 ACTIVE PUBLISHED（前几个为跨店同名组），再放 UNPUBLISHED、DRAFT、m9 SUSPENDED
        slot_defs: list[tuple[str, str, bool]] = []
        for i in range(active_pub_n):
            mid = active_merchants[i % len(active_merchants)]
            slot_defs.append((mid, "PUBLISHED", i < same_active_slots))
        if has_unpub:
            mid = active_merchants[(active_pub_n) % len(active_merchants)]
            slot_defs.append((mid, "UNPUBLISHED", False))
        if has_draft:
            mid = active_merchants[(active_pub_n + 1) % len(active_merchants)]
            slot_defs.append((mid, "DRAFT", False))
        for m9_i in range(m9_quota):
            # 第一个 m9 槽位若所属原型有同名组，则共用同名标题作为硬价格陷阱！
            slot_defs.append(("m9", "PUBLISHED", bool(has_same_name_group and m9_i == 0)))

        used_non_group_titles: set[str] = set()
        for slot_i, (mid, p_status, in_same_group) in enumerate(slot_defs):
            if in_same_group:
                brand = shared_brand
                title = shared_title
                group_tag = same_group_id
            else:
                # 轮转 24 个全量品牌池与类别偏好品牌，确保 24 个品牌全覆盖且同原型内标题多样不重样
                if slot_i % 3 == 2:
                    brand = BRANDS[brand_cursor % len(BRANDS)]
                    brand_cursor += 1
                else:
                    brand = cat_brands[(arch_idx * 3 + slot_i) % len(cat_brands)]
                noun = lex["nouns"][(slot_i + 1) % len(lex["nouns"])]
                candidate_title = f"{brand}{noun}"
                attempt = 0
                while (candidate_title == shared_title or candidate_title in used_non_group_titles) and attempt < 24:
                    attempt += 1
                    brand = BRANDS[(arch_idx * 5 + slot_i + attempt) % len(BRANDS)]
                    noun = lex["nouns"][(slot_i + attempt) % len(lex["nouns"])]
                    candidate_title = f"{brand}{noun}"
                used_non_group_titles.add(candidate_title)
                title = candidate_title
                group_tag = None

            # 组合多样化物理卖点 + 校园场景描述（绝不复制同一句话到20款商品，亦不含任何串号）
            trait_1 = lex["traits"][(slot_i + arch_idx) % len(lex["traits"])]
            trait_2 = lex["traits"][(slot_i + arch_idx + 2) % len(lex["traits"])]
            scene = lex["scenes"][(slot_i * 2 + arch_idx) % len(lex["scenes"])]
            if slot_i % 2 == 0:
                description = f"{trait_1}{scene}"
            else:
                description = f"{scene}{trait_2}"

            product_plans.append(
                {
                    "archetype": arch_key,
                    "category": category,
                    "merchantId": mid,
                    "status": p_status,
                    "brand": brand,
                    "title": title,
                    "description": description,
                    "isSameNameGroup": group_tag,
                    "slotIdx": slot_i,
                    "maxCombos": len(_all_attr_combos(arch_key)),
                }
            )

    if len(product_plans) != 480:
        raise AssertionError(f"商品计划数异常：{len(product_plans)}")

    # 第二步：确定性分配每款商品的 SKU 个数（1..4，且 <= maxCombos），使总 SKU 精确等于 1,020
    # 先给基础个数：maxCombos==2 -> 2；maxCombos==3 -> 2..3；其余按槽位赋予 1, 2, 3, 4
    sku_counts: list[int] = []
    for idx, plan in enumerate(product_plans):
        mc = plan["maxCombos"]
        if plan["status"] != "PUBLISHED" or plan["merchantId"] == "m9":
            cnt = min(mc, 2 if idx % 5 != 0 else 1)
        elif mc >= 16:
            # 多维高组合数原型（如乌龙茶24组合、中性笔18组合、冰红茶16组合）赋满 4 个规格槽位以实现 100% 全属性空间覆盖
            cnt = 4
        elif plan["isSameNameGroup"] is not None:
            cnt = min(mc, 3)
        else:
            pattern = (2, 3, 2, 2, 3, 1, 4, 2)[idx % 8]
            cnt = min(mc, pattern)
        sku_counts.append(cnt)

    target_total_skus = 1020
    # 确定性微调普通商品 SKU 数（保护高维原型 4 槽与跨店同名组 >=2 槽），精确对齐 1,020
    cursor = 0
    while sum(sku_counts) < target_total_skus:
        i = cursor % 480
        cursor += 1
        cap = min(4, product_plans[i]["maxCombos"])
        if product_plans[i]["status"] == "PUBLISHED" and product_plans[i]["merchantId"] != "m9" and sku_counts[i] < cap:
            sku_counts[i] += 1
        if cursor > 20000:
            break
    cursor = 0
    while sum(sku_counts) > target_total_skus:
        i = cursor % 480
        cursor += 1
        plan_i = product_plans[i]
        floor = 4 if (plan_i["status"] == "PUBLISHED" and plan_i["merchantId"] != "m9" and plan_i["maxCombos"] >= 18) else 2
        if sku_counts[i] > floor and plan_i["isSameNameGroup"] is None:
            sku_counts[i] -= 1
        if cursor > 20000:
            break
    if sum(sku_counts) != target_total_skus:
        raise AssertionError(f"SKU 总数未能精确收敛至 {target_total_skus}，当前 {sum(sku_counts)}")

    # 第三步：为每个原型分配具体的 SKU 属性组合，确保：
    # 1) 同一商品内 specKey 100% 唯一；
    # 2) 跨店同名比价组各门店均携带共同旗舰规格（放在健康主力槽位），形成真实多门店同规格价差对比；
    # 3) 12 个 INTENTIONAL_OOS_SPECS 仅以预设无货/停用形态出现，其余 100% 非 OOS 规格组合均有充足现货覆盖！
    by_arch_indices: dict[str, list[int]] = {}
    for idx, plan in enumerate(product_plans):
        by_arch_indices.setdefault(plan["archetype"], []).append(idx)

    planned_skus_by_product: dict[int, list[dict[str, Any]]] = {}

    for arch_key, p_indices in by_arch_indices.items():
        all_combos = _all_attr_combos(arch_key)
        normal_combos = [
            c for c in all_combos
            if (arch_key, tuple(c.items())) not in _INTENTIONAL_OOS_MAP
        ]
        oos_combos = [
            c for c in all_combos
            if (arch_key, tuple(c.items())) in _INTENTIONAL_OOS_MAP
        ]
        flagship = FLAGSHIP_COMPARE_COMBOS.get(arch_key)

        pub_combo_cursor = 0
        aux_combo_cursor = 0
        placed_oos = False

        for local_pos, p_idx in enumerate(p_indices):
            plan = product_plans[p_idx]
            need_k = sku_counts[p_idx]
            is_active_pub = plan["status"] == "PUBLISHED" and plan["merchantId"] != "m9"
            chosen: list[tuple[dict[str, str], str | None]] = []
            seen_tuples: set[tuple[tuple[str, str], ...]] = set()

            # 若该原型含有预设全站 OOS 组合：挂载在非同名组的活跃多SKU商品（或无非同名多SKU时挂在第2家店首槽），以及 m9/UNPUBLISHED 诱饵上
            if oos_combos:
                target_oos = oos_combos[0]
                oos_mode = _INTENTIONAL_OOS_MAP[(arch_key, tuple(target_oos.items()))]["mode"]
                if (
                    is_active_pub
                    and not placed_oos
                    and need_k >= 2
                    and plan["isSameNameGroup"] is None
                ):
                    chosen.append((target_oos, f"INTENTIONAL_{oos_mode}"))
                    seen_tuples.add(tuple(target_oos.items()))
                    placed_oos = True
                elif plan["merchantId"] == "m9" or plan["status"] == "UNPUBLISHED":
                    chosen.append((target_oos, "TRAP_CARRIER"))
                    seen_tuples.add(tuple(target_oos.items()))

            # 跨店同名组（含 m9 同名诱饵）统一在最后一个槽位锁定共同旗舰比价规格（最后槽位受保护不注入缺陷，保证各店均有健康库存可比价！）
            reserve_flagship_tail = (
                flagship is not None
                and plan["isSameNameGroup"] is not None
                and tuple(flagship.items()) not in seen_tuples
            )
            fill_target = need_k - (1 if reserve_flagship_tail else 0)

            guard = 0
            while len(chosen) < fill_target and guard < len(normal_combos) * 4 + 10:
                if is_active_pub:
                    cand = normal_combos[pub_combo_cursor % len(normal_combos)]
                    pub_combo_cursor += 1
                else:
                    cand = normal_combos[aux_combo_cursor % len(normal_combos)]
                    aux_combo_cursor += 1
                guard += 1
                key_t = tuple(cand.items())
                if key_t not in seen_tuples and (not reserve_flagship_tail or cand != flagship):
                    chosen.append((cand, None))
                    seen_tuples.add(key_t)

            if reserve_flagship_tail and flagship is not None:
                chosen.append((flagship, "FLAGSHIP_SHARED"))
                seen_tuples.add(tuple(flagship.items()))

            if len(chosen) != need_k:
                raise AssertionError(f"商品槽位 {p_idx} ({arch_key}) 无法凑齐 {need_k} 个唯一规格")

            planned_skus_by_product[p_idx] = [
                {"attributes": dict(attrs), "specialTag": tag}
                for attrs, tag in chosen
            ]

        if oos_combos and not placed_oos:
            raise AssertionError(f"原型 {arch_key} 的预设 OOS 规格未能挂载到多SKU活跃商品")

    # 第四步：在 410 款活跃已上架商品的普通 SKU 上精确注入定额难负例库存/停用状态，
    # 同时严格保护：
    #   a) 每款 PUBLISHED 商品至少保留 1 个 ACTIVE 且有健康库存（available >= 16）的主力 SKU！
    #   b) 每个原型的每一个 normal_combo 至少保留 >= 1 个（通常 2~5 个）available >= 16 的健康 ACTIVE SKU！
    # 目标总配额（含上述 12 个 INTENTIONAL_OOS_SPECS 中的对应形态）：
    #   - INACTIVE SKU: 精确 60 个
    #   - SOLD_OUT (ACTIVE, onHand=0, reserved=0): 精确 45 个
    #   - RESERVED_FULL (ACTIVE, onHand>0, reserved==onHand): 精确 35 个
    #   - LOW_STOCK (ACTIVE, available in 1..3): 精确 30 个

    # 先统计每个 (arch, combo_tuple) 在活跃已上架商品上的普通候选出现次数
    combo_healthy_supply: dict[tuple[str, tuple[tuple[str, str], ...]], int] = {}
    candidate_defect_slots: list[tuple[int, int]] = []  # (p_idx, s_idx)

    current_inactive = 0
    current_sold_out = 0
    current_reserved_full = 0

    for p_idx, plan in enumerate(product_plans):
        if plan["status"] != "PUBLISHED" or plan["merchantId"] == "m9":
            continue
        skus_plan = planned_skus_by_product[p_idx]
        for s_idx, sp in enumerate(skus_plan):
            tag = sp["specialTag"]
            ckey = (plan["archetype"], tuple(sp["attributes"].items()))
            if tag == "INTENTIONAL_SKU_INACTIVE":
                sp["assignedState"] = "INACTIVE"
                current_inactive += 1
            elif tag == "INTENTIONAL_SOLD_OUT":
                sp["assignedState"] = "SOLD_OUT"
                current_sold_out += 1
            elif tag == "INTENTIONAL_RESERVED_FULL":
                sp["assignedState"] = "RESERVED_FULL"
                current_reserved_full += 1
            else:
                sp["assignedState"] = "HEALTHY"
                combo_healthy_supply[ckey] = combo_healthy_supply.get(ckey, 0) + 1
                # 仅在多SKU商品的非最后一个健康槽位（且非跨店比价旗舰尾槽）挑选缺陷候选，保证每款商品必有 >=1 个 HEALTHY SKU
                if len(skus_plan) >= 2 and s_idx < len(skus_plan) - 1 and tag != "FLAGSHIP_SHARED":
                    candidate_defect_slots.append((p_idx, s_idx))

    import math

    def _assign_defects(target_state: str, needed: int, stride: int, offset: int) -> int:
        assigned = 0
        n_cands = len(candidate_defect_slots)
        while math.gcd(stride, n_cands) != 1:
            stride += 2
        for step in range(n_cands):
            if assigned >= needed:
                break
            p_idx, s_idx = candidate_defect_slots[(offset + step * stride) % n_cands]
            plan = product_plans[p_idx]
            skus_plan = planned_skus_by_product[p_idx]
            sp = skus_plan[s_idx]
            if sp["assignedState"] != "HEALTHY":
                continue
            # 确保该商品至少还剩 1 个 HEALTHY SKU
            healthy_on_prod = sum(1 for x in skus_plan if x["assignedState"] == "HEALTHY")
            if healthy_on_prod <= 1:
                continue
            # 确保该 (archetype, attributes) 全站仍至少保留 1 个 HEALTHY (available>=16) 正例！
            ckey = (plan["archetype"], tuple(sp["attributes"].items()))
            if combo_healthy_supply.get(ckey, 0) <= 1:
                continue
            sp["assignedState"] = target_state
            combo_healthy_supply[ckey] -= 1
            assigned += 1
        if assigned != needed:
            raise AssertionError(f"无法凑足 {target_state} 配额：需要 {needed}，实际分配 {assigned}")
        return assigned

    _assign_defects("INACTIVE", 60 - current_inactive, stride=5, offset=1)
    _assign_defects("SOLD_OUT", 45 - current_sold_out, stride=7, offset=3)
    _assign_defects("RESERVED_FULL", 35 - current_reserved_full, stride=11, offset=6)
    _assign_defects("LOW_STOCK", 30, stride=13, offset=9)

    # 第五步：组装最终的 product_rows 与内存评测元数据 product_meta
    product_rows: list[dict[str, Any]] = []
    product_meta: dict[str, dict[str, Any]] = {}

    for p_idx, plan in enumerate(product_plans):
        p_num = p_idx + 1
        pid = f"vp{p_num:03d}"
        arch_key = plan["archetype"]
        mid = plan["merchantId"]
        p_status = plan["status"]
        day = (p_idx % 28) + 1
        hour = 8 + (p_idx % 12)
        created_at = f"2026-09-{day:02d}T{hour:02d}:00:00Z"

        sku_rows: list[dict[str, Any]] = []
        oos_attrs_on_product: list[dict[str, str]] = []
        oos_mode_on_product: str | None = None

        for s_idx, sp in enumerate(planned_skus_by_product[p_idx]):
            sku_id = f"vs{p_num:03d}_{s_idx + 1}"
            attrs = sp["attributes"]
            spec_key = " ".join(attrs.values())
            price_cent = _compute_price_cent(
                arch_key,
                attrs,
                merchant_id=mid,
                slot_idx=plan["slotIdx"],
                is_same_name=plan["isSameNameGroup"] is not None,
            )

            ckey = (arch_key, tuple(attrs.items()))
            if ckey in _INTENTIONAL_OOS_MAP:
                oos_attrs_on_product.append(dict(attrs))
                oos_mode_on_product = _INTENTIONAL_OOS_MAP[ckey]["mode"]

            if mid == "m9":
                # 停业商户诱饵：库存表面充足、价格极低，但因商户 SUSPENDED 严禁推荐或成交
                sku_status = "ACTIVE"
                on_hand = 28 + ((p_idx + s_idx) % 20)
                reserved = (p_idx + s_idx) % 3
            elif p_status in ("UNPUBLISHED", "DRAFT"):
                sku_status = "ACTIVE"
                on_hand = 20 + ((p_idx + s_idx) % 15) if p_status == "UNPUBLISHED" else 0
                reserved = 0
            else:
                state = sp["assignedState"]
                if state == "INACTIVE":
                    sku_status = "INACTIVE"
                    # 典型场景：低价单件装已停用，但账面仍有旧库存或零库存
                    on_hand = 12 if (p_idx + s_idx) % 2 == 0 else 0
                    reserved = 0
                elif state == "SOLD_OUT":
                    sku_status = "ACTIVE"
                    on_hand = 0
                    reserved = 0
                elif state == "RESERVED_FULL":
                    sku_status = "ACTIVE"
                    lock_qty = 4 + ((p_idx + s_idx) % 7)  # 4..10 全额预占，available == 0
                    on_hand = lock_qty
                    reserved = lock_qty
                elif state == "LOW_STOCK":
                    sku_status = "ACTIVE"
                    avail = ((p_idx + s_idx) % 3) + 1  # available 严格落在 1..3
                    res = (p_idx % 3) + 1
                    on_hand = avail + res
                    reserved = res
                else:
                    sku_status = "ACTIVE"
                    avail = 16 + ((p_idx * 7 + s_idx * 11) % 45)  # available 严格落在 16..60
                    res = (p_idx + s_idx) % 5
                    on_hand = avail + res
                    reserved = res

            sku_rows.append(
                {
                    "skuId": sku_id,
                    "specKey": spec_key,
                    "attributes": attrs,
                    "priceCent": price_cent,
                    "onHand": on_hand,
                    "reserved": reserved,
                    "status": sku_status,
                }
            )

        product_rows.append(
            {
                "productId": pid,
                "merchantId": mid,
                "categoryCode": plan["category"],
                "title": plan["title"],
                "description": plan["description"],
                "status": p_status,
                "createdAt": created_at,
                "skus": sku_rows,
            }
        )

        product_meta[pid] = {
            "archetype": arch_key,
            "siblings": list(ARCHETYPES[arch_key]["siblings"]),
            "brand": plan["brand"],
            "isSameNameGroup": plan["isSameNameGroup"],
            "intentionalOosAttrs": oos_attrs_on_product,
            "intentionalOosMode": oos_mode_on_product,
        }

    return product_rows, product_meta
