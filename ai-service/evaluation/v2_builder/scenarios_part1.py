from __future__ import annotations

DEFAULT_NO_MATCH_TERMS = [
    "没有找到",
    "无法找到",
    "没有匹配",
    "暂无",
    "库存不足",
    "超出预算",
    "无法从当前商品规格核实",
]


def _item(
    *,
    query_type: str,
    family_id: str,
    split: str,
    query: str,
    tags: list[str],
    rationale: str,
    target_archetypes: list[str],
    secondary_archetypes: list[str] | None = None,
    combo_archetypes: list[str] | None = None,
    preferred_merchant_ids: list[str] | None = None,
    prefer_cheapest: bool = False,
    force_no_match: bool = False,
    primary_evidence: list[tuple[str, int]] | None = None,
    secondary_evidence: list[tuple[str, int]] | None = None,
    budget_cent: int | None = None,
    quantity: int | float | None = 1,
    quantity_state: str = "VALID",
    required_attrs: dict[str, str] | None = None,
    forbidden_attrs: dict[str, str] | None = None,
    min_items: int | None = None,
    action: str = "RECOMMEND",
    clarification_terms: list[str] | None = None,
    forbidden_facts: list[str] | None = None,
    no_match_terms: list[str] | None = None,
    context: list[dict[str, str]] | None = None,
    smoke: bool = False,
    disputed: bool = False,
) -> dict:
    """组装单条 V2 场景蓝图字典，确保结构字段完整一致。"""
    primary_ev = list(primary_evidence or [])
    secondary_ev = list(secondary_evidence or [])
    scopes = ["product", "recommendation"]
    if primary_ev:
        scopes.append("knowledge")

    is_fuzzy = query_type == "fuzzy-need-scenario"
    constraints: dict = {
        "budgetCent": budget_cent,
        "quantity": quantity,
        "requiredAttributes": {} if is_fuzzy else dict(required_attrs or {}),
        "forbiddenAttributes": {} if is_fuzzy else dict(forbidden_attrs or {}),
    }
    if min_items is not None:
        constraints["minItems"] = min_items

    resolved_no_match = (
        list(no_match_terms)
        if no_match_terms is not None
        else (list(DEFAULT_NO_MATCH_TERMS) if action == "NO_MATCH" else [])
    )

    return {
        "queryType": query_type,
        "familyId": family_id,
        "split": split,
        "smoke": smoke,
        "tags": list(tags),
        "taskScopes": scopes,
        "originalQuery": query,
        "conversationContext": list(context or []),
        "actorRef": "buyer",
        "intentGold": {"quantityState": quantity_state},
        "constraints": constraints,
        "expectedBehavior": {
            "action": action,
            "clarificationTerms": list(clarification_terms or []),
            "forbiddenFacts": list(forbidden_facts or []),
            "noMatchTerms": resolved_no_match,
        },
        "stateTransition": None,
        "sensitive": False,
        "disputed": disputed,
        "rationale": rationale,
        "goldSpec": {
            "targetArchetypes": list(target_archetypes),
            "secondaryArchetypes": list(secondary_archetypes or []),
            "comboArchetypes": list(combo_archetypes or []),
            "goldRequiredAttributes": dict(required_attrs or {}),
            "goldForbiddenAttributes": dict(forbidden_attrs or {}),
            "preferredMerchantIds": list(preferred_merchant_ids) if preferred_merchant_ids is not None else None,
            "preferCheapest": prefer_cheapest,
            "forceNoMatch": force_no_match,
            "primaryEvidence": primary_ev,
            "secondaryEvidence": secondary_ev,
        },
    }


